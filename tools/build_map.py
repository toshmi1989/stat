"""Builds app/static/uzmap.js (outlines of the 14 regions of Uzbekistan) from the open geoBoundaries ADM1 file (CC BY 4.0).
Usage: python3 tools/build_map.py geoBoundaries-UZB-ADM1_simplified.geojson
Source: https://github.com/wmgeolab/geoBoundaries  (gbOpen / UZB / ADM1)"""
import json, math, sys

ISO = {"UZ-QR": 1, "UZ-AN": 2, "UZ-BU": 3, "UZ-JI": 4, "UZ-QA": 5, "UZ-NW": 6, "UZ-NG": 7, "UZ-SA": 8, "UZ-SU": 9, "UZ-SI": 10, "UZ-TO": 11, "UZ-FA": 12, "UZ-XO": 13, "UZ-TK": 14}  # = ids of regions in app/db.py REGIONS order
K = math.cos(math.radians(41.3))   # a plain equirectangular projection corrected for the latitude


def dp(pts, eps):
    if len(pts) < 3:
        return pts
    (x1, y1), (x2, y2) = pts[0], pts[-1]
    dx, dy = x2 - x1, y2 - y1
    n = math.hypot(dx, dy) or 1e-12
    i, dmax = 0, 0
    for k in range(1, len(pts) - 1):
        d = abs(dy * pts[k][0] - dx * pts[k][1] + x2 * y1 - y2 * x1) / n
        if d > dmax:
            i, dmax = k, d
    if dmax > eps:
        return dp(pts[:i + 1], eps)[:-1] + dp(pts[i:], eps)
    return [pts[0], pts[-1]]


def area_centroid(r):
    a = cx = cy = 0
    for (x0, y0), (x1, y1) in zip(r, r[1:] + r[:1]):
        f = x0 * y1 - x1 * y0
        a += f; cx += (x0 + x1) * f; cy += (y0 + y1) * f
    a /= 2
    return abs(a), (cx / (6 * a), cy / (6 * a)) if a else r[0]


g = json.load(open(sys.argv[1]))
out = {}
allp = [(lon * K, -lat) for f in g["features"] for poly in (f["geometry"]["coordinates"] if f["geometry"]["type"] == "MultiPolygon" else [f["geometry"]["coordinates"]]) for ring in poly for lon, lat in ring]
x0, y0 = min(p[0] for p in allp), min(p[1] for p in allp)
W, H = max(p[0] for p in allp) - x0, max(p[1] for p in allp) - y0
S = 1000 / W
for f in g["features"]:
    rid = ISO[f["properties"]["shapeISO"]]
    polys = f["geometry"]["coordinates"] if f["geometry"]["type"] == "MultiPolygon" else [f["geometry"]["coordinates"]]
    d, best = [], (0, None)
    for poly in polys:
        for ri, ring in enumerate(poly):
            pts = [((lon * K - x0) * S, (-lat - y0) * S) for lon, lat in ring]
            if pts[0] == pts[-1]:
                pts = pts[:-1]
            k = max(range(len(pts)), key=lambda j: math.hypot(pts[j][0] - pts[0][0], pts[j][1] - pts[0][1]))   # a closed ring: split at the farthest point, else the chord is degenerate
            pts = dp(pts[:k + 1], 0.9)[:-1] + dp(pts[k:] + [pts[0]], 0.9)[:-1]
            if len(pts) < 3:
                continue
            d.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z")
            if ri == 0:
                a, c = area_centroid(pts)
                if a > best[0]:
                    best = (a, c)
    if best[1] is None: print("EMPTY", f["properties"]["shapeName"], len(d)); continue
    out[rid] = {"d": "".join(d), "c": [round(best[1][0], 1), round(best[1][1], 1)]}
js = "// generated by tools/build_map.py from geoBoundaries (CC BY 4.0); keys are region ids of app/db.py\nwindow.UZMAP = " + json.dumps({"w": 1000, "h": round(H * S, 1), "r": out}, ensure_ascii=False, separators=(",", ":")) + ";\n"
open("app/static/uzmap.js", "w").write(js)
print(len(js), "bytes; viewBox", 1000, round(H * S))
